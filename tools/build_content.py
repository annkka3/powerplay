#!/usr/bin/env python3
"""Builds the app data from tools/source/parts:
- data/grammar.json  — 45 grammar topics (grammar_g*.json), checked for structure;
- js/vocab.js        — TOPICS and WORDS (vocab_*.json), a word that appears in two topics stays in the first;
- js/art_files.js    — which generated pictures exist in img/ (players, coach poses, comics).
Run: python3 tools/build_content.py"""
import json, pathlib, re, sys
ROOT = pathlib.Path(__file__).resolve().parent.parent
P = ROOT / 'tools/source/parts'
problems = []

# ---------- grammar ----------
syl = {t['id']: t for t in json.loads((ROOT / 'tools/source/grammar_syllabus.json').read_text(encoding='utf8'))}
topics = []
for f in sorted(P.glob('grammar_g*.json')):
    topics += json.loads(f.read_text(encoding='utf8'))
topics.sort(key=lambda t: t['id'])
ids = set()
for t in topics:
    s = syl[t['id']]
    for k in ('stage', 'title_ru', 'goal_ru', 'prereq', 'spotlight'):
        t[k] = s[k]
    for it in t['items']:
        if it['id'] in ids: problems.append('duplicate ' + it['id'])
        ids.add(it['id'])
        if it['t'] == 'text':   # the passage key differs between writers
            for k in ('text', 'passage', 'body', 'tx'):
                if isinstance(it.get(k), str): it['text'] = it.pop(k) if k != 'text' else it['text']; break
            if it['text'].count('___') != len(it['a']): problems.append('text gaps ' + it['id'])
        if it['t'] == 'chat':
            n = sum(l['t'].count('___') for l in it['lines'])
            if n != len(it['a']): problems.append('chat gaps ' + it['id'])
        if it['t'] in ('mc', 'listen') and not (0 <= it['a'] < len(it['o'])): problems.append('mc index ' + it['id'])
        if it['t'] == 'gap' and '___' not in it['q']: problems.append('gap without ___ ' + it['id'])
        if it['t'] == 'err' and not (0 <= it['bad'] < len(it['s'].split(' '))): problems.append('err index ' + it['id'])
        if it['tag'] not in t['tags']: problems.append('tag ' + it['id'])
        for k in ('a',):
            if it['t'] in ('gap', 'tr', 'ru2en') and isinstance(it.get(k), str): it[k] = [it[k]]
missing = sorted(set(syl) - {t['id'] for t in topics})
if missing: problems.append('missing topics ' + ','.join(missing))
(ROOT / 'data').mkdir(exist_ok=True)
(ROOT / 'data/grammar.json').write_text(json.dumps(topics, ensure_ascii=False, separators=(',', ':')), encoding='utf8')
print('grammar topics', len(topics), 'items', sum(len(t['items']) for t in topics))

# ---------- vocabulary ----------
TOPICS = [
    ('01', 'Привет и основа', '👋'), ('02', 'Главные глаголы', '⚡'), ('03', 'Мой день', '⏰'), ('04', 'Игры и интернет', '🎮'),
    ('05', 'Хоккей и спорт', '🏒'), ('06', 'Музыка и хобби', '🎧'), ('07', 'Школа и учёба', '📚'), ('08', 'Семья и друзья', '👪'),
    ('09', 'Дом и вещи', '🏠'), ('10', 'Еда и напитки', '🍔'), ('11', 'Город и дорога', '🏙️'), ('12', 'Путешествия и транспорт', '✈️'),
    ('13', 'Покупки, одежда, деньги', '🛍️'), ('14', 'Тело и здоровье', '🩺'), ('15', 'Природа, погода, животные', '🦖'), ('16', 'Время и числа', '🕒'),
    ('17', 'Какой? Описания', '📏'), ('18', 'Чувства и характер', '😎'), ('19', 'Где и когда: связки', '🔗'), ('20', 'Новая страна и жизнь', '🗺️'),
]
words, seen = [], {}
for f in sorted(P.glob('vocab_*.json')):
    for w in json.loads(f.read_text(encoding='utf8')):
        k = w['en'].strip().lower()
        # the same word with a different meaning (book: книга / бронировать) stays as a separate card
        ru = set(x for x in re.findall(r'[а-яё]{3,}', w['ru'].lower()))
        if any(ru & r for r in seen.get(k, [])): continue
        seen.setdefault(k, []).append(ru)
        words.append({'id': 'w' + w['id'][1:], 'tp': w['topic'], 'en': w['en'], 'ru': w['ru'], 'ipa': w.get('ipa', ''), 'pos': w.get('pos', ''), 'lv': w.get('lv', ''), 'ex': w.get('ex', ''), 'exru': w.get('exru', ''), 'e': w.get('e', '')})
order = {t[0]: i for i, t in enumerate(TOPICS)}
# new words come in a sensible order: A1 words of the most useful topics first, within a level the deck order
TRAVEL = ['01', '02', '05', '04', '03', '08', '10', '07', '06', '16', '17', '18', '09', '11', '12', '13', '14', '15', '19', '20']
rank = {t: i for i, t in enumerate(TRAVEL)}
lvr = {'A1': 0, 'A2': 1, 'B1': 2}
words.sort(key=lambda w: (lvr.get(w['lv'], 1), rank[w['tp']], w['id']))
out = ['/* Generated by tools/build_content.py from tools/source/parts/vocab_*.json. Do not edit by hand.',
       '   WORDS are in learning order: A1 first, the most useful topics first. */',
       'const TOPICS = ' + json.dumps([{'id': a, 'ru': b, 'e': c} for a, b, c in TOPICS], ensure_ascii=False) + ';',
       'const WORDS = [']
out += [json.dumps(w, ensure_ascii=False) + ',' for w in words]
out.append('];')
(ROOT / 'js/vocab.js').write_text('\n'.join(out) + '\n', encoding='utf8')
print('words', len(words))

# ---------- pictures ----------
img = ROOT / 'img'
art = {'players': {}, 'coach': {}, 'chars': {}, 'comics': {}}
for f in sorted((img / 'chars').glob('*.webp')) if (img / 'chars').exists() else []:
    art['chars'][f.stem] = 'img/chars/' + f.name
for f in sorted((img / 'players').glob('*.webp')) if (img / 'players').exists() else []:
    art['players'][f.stem] = 'img/players/' + f.name
for f in sorted((img / 'coach').glob('*.webp')) if (img / 'coach').exists() else []:
    art['coach'][f.stem] = 'img/coach/' + f.name
for d in sorted((img / 'comics').glob('*')) if (img / 'comics').exists() else []:
    if d.is_dir(): art['comics'][d.name] = sorted('img/comics/' + d.name + '/' + f.name for f in d.glob('*.webp'))
(ROOT / 'js/art_files.js').write_text('/* Generated by tools/build_content.py: the pictures that exist in img/. */\nconst ART_FILES = ' + json.dumps(art, ensure_ascii=False) + ';\n', encoding='utf8')

# ---------- comics ----------
# tools/source/comics: cast.json (who speaks, which macOS voice), gloss_<series>.json (tap-to-translate words and
# phrases) and one file per episode. Words marked "new" go to the vocabulary topic «Из комиксов» (id cm-…).
C = ROOT / 'tools/source/comics'
TOKEN = re.compile(r"[A-Za-z][A-Za-z'’]*(?:-[A-Za-z]+)*")
by_en = {w['en'].lower(): w for w in words}
by_id = {w['id']: w for w in words}
cast = json.loads((C / 'cast.json').read_text(encoding='utf8'))
gloss, cm_words, episodes = {}, {}, []
def cm_word(en, ru, e, line):
    wid = 'cm-' + re.sub(r'[^a-z0-9]+', '-', en.lower()).strip('-')
    if wid not in cm_words:
        cm_words[wid] = {'id': wid, 'tp': 'cm', 'en': en, 'ru': ru, 'pos': '', 'lv': 'A1', 'e': e or '💬', 'cm': 1}
    w = cm_words[wid]
    if line and 'ex' not in w: w['ex'], w['exru'] = line['en'], line['ru']
    return wid
for f in sorted(C.glob('gloss_*.json')):
    gloss[f.stem[6:]] = json.loads(f.read_text(encoding='utf8'))
for f in sorted(C.glob('*_[0-9][0-9].json')):
    ep = json.loads(f.read_text(encoding='utf8'))
    g = gloss[ep['series']]
    lines = [l for p_ in ep['panels'] for l in p_['lines']]
    pics = [ROOT / 'img/comics' / ep['id'] / (p_['img'] + '.webp') for p_ in ep['panels']]
    if not all(x.exists() for x in pics):
        print('comic', ep['id'], 'waits for pictures'); continue
    for p_ in ep['panels']: p_['img'] = 'img/comics/' + ep['id'] + '/' + p_['img'] + '.webp'
    for l in lines:
        if l['who'] not in cast: problems.append(ep['id'] + ': unknown speaker ' + l['who'])
        for k in ('x', 'y', 'w'):
            if not (0 <= l.get(k, -1) <= 100): problems.append(ep['id'] + ': bubble position ' + l['en'])
        for tok in TOKEN.findall(l['en']):
            key = tok.lower().replace('’', "'")
            gw = g['words'].get(key)
            if not gw: problems.append(f"{ep['id']}: no gloss for «{tok}» in {l['en']}"); continue
            if gw.get('w') == 'new': gw['w'] = cm_word(gw.get('l', key), gw.get('wru') or (g['words'].get(gw.get('l', ''), {}).get('wru')) or gw['ru'], gw.get('e') or g['words'].get(gw.get('l', ''), {}).get('e'), l)
            elif gw.get('w') and gw['w'] not in by_id and not gw['w'].startswith('cm-'): problems.append('gloss ' + key + ': no word ' + gw['w'])
        for ph in g['phrases']:
            if ph['en'] in l['en'].lower().replace('’', "'"):
                if ph.get('w') == 'auto':
                    if ph['en'] in by_en: ph['w'] = by_en[ph['en']]['id']
                    else: problems.append('phrase not in vocabulary: ' + ph['en'])
                elif ph.get('w') == 'new': ph['w'] = cm_word(ph['en'], ph['ru'], ph.get('e'), l)
    for it in ep['quiz']:
        if it['t'] == 'mc' and not (0 <= it['a'] < len(it['o'])): problems.append(it['id'] + ' mc answer')
        if it['t'] == 'err' and it['s'].split(' ')[it['bad']].strip('.,!?').lower() == it['fix'].lower(): problems.append(it['id'] + ' err')
    episodes.append(ep)
for g in gloss.values():   # words of episodes without pictures yet stay unresolved; drop the markers
    for gw in g['words'].values():
        if gw.get('w') == 'new': gw.pop('w')
    for ph in g['phrases']:
        if ph.get('w') in ('new', 'auto'): ph.pop('w')
(ROOT / 'js/comics_data.js').write_text('\n'.join([
    '/* Generated by tools/build_content.py from tools/source/comics. Do not edit by hand. */',
    'const COMIC_CAST = ' + json.dumps(cast, ensure_ascii=False) + ';',
    'const COMIC_GLOSS = ' + json.dumps(gloss, ensure_ascii=False) + ';',
    'const COMIC_WORDS = ' + json.dumps(list(cm_words.values()), ensure_ascii=False) + ';',
    'const COMICS = ' + json.dumps(episodes, ensure_ascii=False) + ';', '']), encoding='utf8')
print('comics', len(episodes), 'episodes,', len(cm_words), 'new words')

if problems:
    print('PROBLEMS:'); [print(' -', p) for p in problems]
